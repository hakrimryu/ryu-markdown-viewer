import { _electron as electron } from 'playwright';
import electronPath from 'electron';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

const cwd = process.cwd();
const base = path.join(cwd, '.test-data');
await fs.mkdir(base, { recursive: true });
const run = await fs.mkdtemp(path.join(base, 'editing-'));
const folder = path.join(run, 'documents');
const data = path.join(run, 'settings');
await fs.mkdir(folder); await fs.mkdir(data);
const file = path.join(folder, 'original.md');
const other = path.join(folder, 'other.md');
const created = path.join(folder, '새 문서.md');
await fs.writeFile(file, '\uFEFF# Original\r\n\r\nText\r\n');
await fs.writeFile(other, '# Other');
await fs.writeFile(path.join(data, 'workspace.json'), JSON.stringify({ roots: [folder], session: { tabs: [file, other], active: file, language: 'ko' } }));
const env = { ...process.env, MARKDESK_DATA_DIR: data };
delete env.ELECTRON_RUN_AS_NODE;
let app; let succeeded = false;
const errors = [];
try {
  app = await electron.launch({ executablePath: electronPath, args: [cwd], cwd, env });
  const page = await app.firstWindow();
  page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  await page.locator('#document h1').waitFor();
  await page.locator('#edit-toggle').click();
  const editor = page.locator('#markdown-editor');
  await editor.fill('/');
  await page.locator('#slash-menu').waitFor();
  assert.ok(await page.locator('#slash-menu [role="option"]').count() >= 15);
  await page.keyboard.type('heading');
  assert.equal(await page.locator('#slash-menu [role="option"]').count(), 3, 'typing narrows commands');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  assert.equal(await editor.inputValue(), '## ');
  await page.keyboard.press('Control+z');
  assert.equal(await editor.inputValue(), '/heading', 'snippet insertion supports undo');
  await editor.fill('/code');
  await page.locator('#slash-menu [role="option"]').click();
  assert.equal(await editor.inputValue(), '```\n\n```');
  assert.equal(await editor.evaluate(el => el.selectionStart), 4, 'caret is inside the code block');
  await editor.fill('/');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#slash-menu').isHidden(), true);
  await page.keyboard.type('ordinary/path');
  assert.equal(await editor.inputValue(), '/ordinary/path', 'ordinary typing does not insert a command');
  await editor.fill('# Draft\n\n한글 편집');
  await page.locator('[data-tab]').filter({ hasText: 'other.md' }).click();
  await page.waitForFunction(() => document.querySelector('#markdown-editor').value === '# Other');
  await page.locator('[data-tab]').filter({ hasText: 'original.md' }).click();
  assert.equal(await editor.inputValue(), '# Draft\n\n한글 편집', 'draft survives tab changes');
  await fs.writeFile(path.join(folder, 'watcher.md'), '# Watcher');
  await page.locator('[data-file]').filter({ hasText: 'watcher.md' }).waitFor();
  assert.equal(await editor.inputValue(), '# Draft\n\n한글 편집', 'watcher keeps the draft');
  await page.keyboard.press('Control+s');
  await page.waitForFunction(() => document.querySelector('#save-file').disabled && !document.querySelector('[aria-selected="true"].tab').textContent.includes('•'));
  assert.equal(await fs.readFile(file, 'utf8'), '\uFEFF# Draft\r\n\r\n한글 편집');
  await page.locator('#edit-toggle').click();
  await page.locator('#document h1').filter({ hasText: 'Draft' }).waitFor();
  await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }); }, created);
  await page.keyboard.press('Control+n');
  await editor.waitFor();
  await page.waitForFunction(() => document.querySelector('#markdown-editor').value === '');
  assert.equal(await fs.readFile(created, 'utf8'), '');
  await page.locator('[data-file]').filter({ hasText: '새 문서.md' }).waitFor();
  await editor.fill('/표');
  assert.equal(await page.locator('#slash-menu [role="option"]').count(), 1, 'localized search works');
  await page.keyboard.press('Tab');
  assert.match(await editor.inputValue(), /^\| A \| B \|/);
  await page.keyboard.press('Control+s');
  await page.waitForFunction(() => document.querySelector('#save-file').disabled && !document.querySelector('[aria-selected="true"].tab').textContent.includes('•'));
  await editor.fill('# Draft conflicting');
  await fs.writeFile(created, '# External');
  await page.keyboard.press('Control+s');
  await page.locator('#toast').filter({ hasText: '외부에서' }).waitFor();
  assert.equal(await fs.readFile(created, 'utf8'), '# External');
  assert.equal(await editor.inputValue(), '# Draft conflicting');
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 2 }); });
  await page.keyboard.press('Control+w');
  assert.equal(await editor.inputValue(), '# Draft conflicting', 'cancel keeps a dirty tab');
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }); });
  await page.keyboard.press('Control+w');
  await page.waitForFunction(() => ![...document.querySelectorAll('[data-tab]')].some(el => el.dataset.tab.endsWith('새 문서.md')));
  await page.locator('[data-tab]').filter({ hasText: 'original.md' }).click();
  await page.waitForFunction(() => document.querySelector('#markdown-editor').value.startsWith('# Draft\n') && !document.querySelector('#markdown-editor').readOnly);
  await editor.fill('# Save on close');
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); });
  await page.keyboard.press('Control+w');
  await page.waitForFunction(() => document.querySelectorAll('[data-tab]').length === 1);
  await page.waitForFunction(() => document.querySelector('#markdown-editor').value === '# Other' && !document.querySelector('#markdown-editor').readOnly);
  assert.equal(await fs.readFile(file, 'utf8'), '\uFEFF# Save on close');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 650));
  await page.waitForFunction(() => innerWidth === 900);
  await editor.fill('/');
  await page.locator('#slash-menu').waitFor();
  const layout = await page.evaluate(() => {
    const menu = document.querySelector('#slash-menu').getBoundingClientRect();
    const toolbar = document.querySelector('.document-actions').getBoundingClientRect();
    return menu.left >= 0 && menu.right <= innerWidth && menu.bottom < innerHeight && toolbar.right <= innerWidth && document.body.scrollWidth <= innerWidth;
  });
  assert.ok(layout, 'editor, commands and toolbar fit a narrow window');
  await fs.mkdir(path.join(cwd, 'artifacts'), { recursive: true });
  await page.screenshot({ path: path.join(cwd, 'artifacts', 'markdesk-editing.png') });
  await page.keyboard.press('Escape');
  await editor.fill('# Exit draft');
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 2 }); });
  await page.locator('[data-window="close"]').click();
  assert.equal(await editor.inputValue(), '# Exit draft', 'cancel keeps the app open');
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); });
  await page.locator('[data-window="close"]').click();
  if (app.process().exitCode === null) await new Promise(resolve => app.process().once('exit', resolve));
  assert.equal(await fs.readFile(other, 'utf8'), '# Exit draft', 'window close saves the draft before quitting');
  assert.deepEqual(errors, []);
  app = undefined; succeeded = true;
  console.log('PASS: slash completion, keyboard/mouse selection, undo, ordinary typing, localized filtering, drafts, safe saves, new files, conflicts, close prompts and narrow layout.');
} catch (error) {
  if (app) {
    const page = await app.firstWindow().catch(() => null);
    if (page) console.error(await page.evaluate(() => ({ active: document.querySelector('.tab.active')?.textContent, editor: document.querySelector('#markdown-editor')?.value, status: document.querySelector('#status-position')?.textContent })));
  }
  throw error;
} finally {
  if (app) {
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }); }).catch(() => {});
    await app.close();
  }
  if (succeeded && path.dirname(run) === base) await fs.rm(run, { recursive: true, force: true });
}
